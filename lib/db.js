function sqliteAdapter(db){return {
  async all(sql,params=[]){return db.prepare(sql).all(...params);},
  async get(sql,params=[]){return db.prepare(sql.replace(/\s+FOR UPDATE\s*$/i,"")).get(...params)||null;},
  async run(sql,params=[]){const statement=db.prepare(sql);if(/\bRETURNING\b/i.test(sql)){const row=statement.get(...params);return {changes:row?1:0,lastInsertRowid:row?.id===undefined?undefined:Number(row.id)};}const result=statement.run(...params);return {changes:result.changes,lastInsertRowid:Number(result.lastInsertRowid)};},
};}
function postgresAdapter(client){return {
  async all(sql,params=[]){await ready();return normalizeRows((await client.query(toPostgres(sql),params)).rows);},
  async get(sql,params=[]){await ready();return normalizeRows((await client.query(toPostgres(sql),params)).rows)[0]||null;},
  async run(sql,params=[]){await ready();const result=await client.query(toPostgres(sql),params);return {changes:result.rowCount,lastInsertRowid:result.rows?.[0]?.id===undefined?undefined:Number(result.rows[0].id)};},
};}

async function all(sql,params=[]){if(pool)return postgresAdapter(pool).all(sql,params);return withSqliteLock(()=>sqliteAdapter(openSqlite()).all(sql,params));}
async function get(sql,params=[]){if(pool)return postgresAdapter(pool).get(sql,params);return withSqliteLock(()=>sqliteAdapter(openSqlite()).get(sql,params));}
async function run(sql,params=[]){if(pool)return postgresAdapter(pool).run(sql,params);return withSqliteLock(()=>sqliteAdapter(openSqlite()).run(sql,params));}
async function transaction(work){
  if(!pool)return withSqliteLock(async()=>{const db=openSqlite();db.exec("BEGIN IMMEDIATE");try{const result=await work(sqliteAdapter(db));db.exec("COMMIT");return result;}catch(error){db.exec("ROLLBACK");throw error;}});
  await ready();const client=await pool.connect();
  try{await client.query("BEGIN");const result=await work(postgresAdapter(client));await client.query("COMMIT");return result;}
  catch(error){await client.query("ROLLBACK");throw error;}
  finally{client.release();}
}

export default {all,get,run,transaction};
