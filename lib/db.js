let sqliteDb;
function openSqlite(){
  if(sqliteDb)return sqliteDb;
  if(process.env.NODE_ENV==="production")throw new Error("Set SUPABASE_DB_URL to the Supabase Postgres connection string in production.");
  const dataPath=process.env.SMARTBUS_DB_PATH||join(process.cwd(),"data","smartbus.sqlite");mkdirSync(dirname(dataPath),{recursive:true});
  sqliteDb=new Database(dataPath);sqliteDb.pragma("busy_timeout=5000");sqliteDb.pragma("journal_mode=WAL");sqliteDb.pragma("foreign_keys=ON");sqliteDb.exec(sqliteSchema);seedDemoData(sqliteDb);return sqliteDb;
}

const connectionString=process.env.SUPABASE_DB_URL;
const pool=connectionString?new Pool({connectionString,max:5}):null;
let schemaReady;
let sqliteQueue=Promise.resolve();
async function withSqliteLock(work){
  let release;const previous=sqliteQueue;sqliteQueue=new Promise((resolve)=>{release=resolve;});await previous;
  try{return await work();}finally{release();}
}
function toPostgres(sql){let index=0;return sql.replace(/\?/g,()=>`$${++index}`);}
function normalizeRows(rows){return rows.map((row)=>Object.fromEntries(Object.entries(row).map(([key,value])=>[key,["n","stop_count","max_seat","expires_at","attempted_at"].includes(key)&&value!==null?Number(value):value])));}
async function ready(){
  if(!pool)return;
  if(!schemaReady)schemaReady=(async()=>{
    await pool.query(postgresSchema);
    const email=process.env.SMARTBUS_ADMIN_EMAIL?.trim().toLowerCase(),password=process.env.SMARTBUS_ADMIN_PASSWORD;
    if(email&&password&&password.length>=16)await pool.query("INSERT INTO users(name,email,password_hash,role,created_at) VALUES($1,$2,$3,'admin',$4) ON CONFLICT(email) DO NOTHING",["SmartBus Admin",email,hashPassword(password),new Date().toISOString()]);
    await seedPostgresData();
  })();
  await schemaReady;
}
